const BRACKET_REGEX = /\[([^\]]+)\]/g

/**
 * 智能语义情绪分析兜底：当表情词汇未被静态映射完全命中时，
 * 提取核心词根并映射为对应的情感 Emoji，彻底杜绝 [xxx] 方框代码残留。
 */
function resolveSemanticFallbackEmoji(phrase: string): string | null {
  const p = phrase.trim()

  // 1. 笑脸与快乐情绪
  if (/笑|哈|乐|喜|嘻|嘿|高兴|嗨|灿烂|爽/.test(p)) return '😄'
  // 2. 哭泣与眼泪
  if (/哭|泪|泣|伤心|绝望|破防|碎|惨|呜/.test(p)) return '😭'
  // 3. 爱心与心动
  if (/爱|心|恋|喜欢|表白|么么|亲/.test(p)) return '❤️'
  // 4. 点赞、棒、牛、赞同
  if (/赞|强|棒|牛|顶|厉|好|优秀|给力|胜|耶|6/.test(p)) return '👍'
  // 5. 愤怒与生气
  if (/怒|气|火|暴|愤|恼|炸|骂/.test(p)) return '😡'
  // 6. 震惊与惊讶
  if (/惊|呆|吓|愕|哇|噢|天|雷|炸/.test(p)) return '😲'
  // 7. 委屈与可怜
  if (/委屈|可怜|弱|衰|害羞|萌|无辜/.test(p)) return '🥺'
  // 8. 困倦与睡觉
  if (/困|睡|梦|眠|安|乏/.test(p)) return '😴'
  // 9. 思考与困惑
  if (/思|想|惑|疑|问|摸不透|纠结/.test(p)) return '🤔'
  // 10. 汗颜与尴尬
  if (/汗|尬|无语|黑线|抹汗/.test(p)) return '😅'
  // 11. 晕厥与眩晕
  if (/晕|迷|醉|懵|癫/.test(p)) return '😵'
  // 12. 柠檬与酸
  if (/酸|柠/.test(p)) return '🍋'
  // 13. 动物类 (狗/猫/猪)
  if (/狗|汪|哈士奇|柴/.test(p)) return '🐶'
  if (/猫|喵/.test(p)) return '🐱'
  if (/猪/.test(p)) return '🐷'
  // 14. 音乐与演出
  if (/歌|音|曲|唱|弹|奏|乐/.test(p)) return '🎵'
  // 15. 拜托与祈祷
  if (/拜|谢|祈|求|保佑|合十/.test(p)) return '🙏'
  // 16. 美食与干饭
  if (/吃|饭|馋|香|饿|食|肉|火锅|奶茶/.test(p)) return '😋'
  // 17. 庆祝与酒水
  if (/酒|杯|饮|醉|干/.test(p)) return '🍻'
  // 18. 星光与闪耀
  if (/星|光|闪|妙|神/.test(p)) return '✨'
  // 19. 拥抱
  if (/抱/.test(p)) return '🫂'
  // 20. 挥手告别
  if (/走|跑|溜|拜拜|再见|飞/.test(p)) return '👋'

  return null
}

/**
 * 将评论内容中的表情文本代码解析为纯正自然 Emoji 符号
 * 绝对杜绝出现 "[xxx]" 的丑陋方框
 * @param content 原始评论文本
 * @returns 替换后的自然 Emoji 文本
 */
export function parseCommentEmoji(content?: string): string {
  if (!content) return ''

  return content.replace(BRACKET_REGEX, (match, inner) => {
    // 1. 精确命中收录字典
    if (COMMENT_EMOJI_MAP[match]) {
      return COMMENT_EMOJI_MAP[match]
    }

    // 2. 大小写或两端空白容错匹配
    const trimmedMatch = `[${inner.trim()}]`
    if (COMMENT_EMOJI_MAP[trimmedMatch]) {
      return COMMENT_EMOJI_MAP[trimmedMatch]
    }

    // 3. 智能语义情绪分析兜底
    const semanticFallback = resolveSemanticFallbackEmoji(inner)
    if (semanticFallback) {
      return semanticFallback
    }

    // 4. 对于无法识别的方括号纯表情码 (通常为 1~8 字符短语，如 [某某])，
    // 去除方框直接转为友好 Emoji 或自然纯文本，彻底杜绝 "[xxx]" 方框破损出戏
    const isTagLike = inner.length <= 8 && !/[\n\r]/.test(inner)
    if (isTagLike) {
      return '✨'
    }

    // 其余长句或包含换行符的内容保留
    return match
  })
}

/**
 * 提取评论对象携带的表情包贴纸 URL
 * @param comment 原始评论对象
 */
export function extractExpressionUrl(comment: any): string | null {
  if (!comment) return null
  return (
    comment?.expressionUrl ||
    comment?.contentResource?.expressionUrl ||
    comment?.contentStickerExt?.expressionUrl ||
    comment?.contentStickerExt?.picUrl ||
    null
  )
}
